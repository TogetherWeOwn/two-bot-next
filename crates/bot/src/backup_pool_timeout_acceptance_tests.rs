#[tokio::test]
async fn malformed_url_still_refused_with_existing_constant() {
    let error = open_pool_with_tls("fixture-marker not a url", TlsPolicy::LocalOnly)
        .await
        .unwrap_err();
    assert_eq!(error, "invalid database URL");
    assert!(!error.contains("fixture-marker"), "refusal echoed the URL");
}
