use std::time::Duration;

use super::open_pool_with_tls;
use two_bot_core::database_tls::TlsPolicy;

/// Outer bound for the hung-database refusal. sqlx 0.9 defaults to a 30 s
/// acquire timeout, so a pool without the triple hangs past this bound; any
/// documented acquire bound under 20 s (precedents: 2-10 s) refuses inside it.
const REFUSAL_BOUND: Duration = Duration::from_secs(20);

/// Fixed refusal for a failed open, reused by the eager hung-database path.
const CONNECT_REFUSED: &str = "cannot connect; database details redacted";

/// A hung Postgres: accepts TCP and never speaks the protocol.
async fn start_hung_db() -> (u16, tokio::task::JoinHandle<()>) {
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0")
        .await
        .expect("bind hung-database stub");
    let port = listener
        .local_addr()
        .expect("hung-database stub address")
        .port();
    let task = tokio::spawn(async move {
        loop {
            let accepted = listener.accept().await;
            let Ok((socket, _)) = accepted else {
                break;
            };
            tokio::spawn(async move {
                tokio::time::sleep(Duration::from_secs(3600)).await;
                drop(socket);
            });
        }
    });
    (port, task)
}

fn hung_url(port: u16) -> String {
    format!("postgres://hung_probe:fixture-hung-password@127.0.0.1:{port}/hung_db")
}

#[tokio::test]
async fn hung_database_refuses_within_bound_instead_of_hanging() {
    let (port, hung) = start_hung_db().await;
    let url = hung_url(port);
    let outcome = tokio::time::timeout(REFUSAL_BOUND, async {
        match open_pool_with_tls(&url, TlsPolicy::LocalOnly).await {
            Err(fixed) => assert_eq!(
                fixed, CONNECT_REFUSED,
                "eager open must reuse the existing fixed refusal"
            ),
            Ok(pool) => {
                let error = sqlx::query_scalar::<_, i32>("SELECT 1")
                    .fetch_one(&pool)
                    .await
                    .unwrap_err();
                pool.close().await;
                assert!(
                    matches!(error, sqlx::Error::PoolTimedOut),
                    "first checkout must refuse with PoolTimedOut, got {error:?}"
                );
            }
        }
    })
    .await;
    hung.abort();
    let bound_secs = REFUSAL_BOUND.as_secs();
    assert!(
        outcome.is_ok(),
        "hung database must refuse within {bound_secs} s, not hang"
    );
}

/// The `open_pool` family source: all three pool constructors live here.
fn pool_open_source() -> String {
    let source = std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/src/backup_cli.rs"))
        .expect("read backup_cli.rs");
    let start = source
        .find("async fn open_pool(")
        .expect("open_pool must exist in backup_cli.rs");
    let end = source[start..]
        .find("fn load_staging_token")
        .map(|offset| start + offset)
        .expect("pool-open segment must end before load_staging_token");
    source[start..end].to_owned()
}

#[test]
fn pool_open_sets_max_connections() {
    let segment = pool_open_source();
    assert!(
        segment.contains("max_connections"),
        "open_pool_with_tls must set documented max_connections:\n{segment}"
    );
}

