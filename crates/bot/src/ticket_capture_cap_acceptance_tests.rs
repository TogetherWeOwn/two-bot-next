use super::*;
use crate::discord_test_common::{MockRest, ScriptedResponse};
use serde_json::json;
use sqlx::postgres::PgPoolOptions;

/// Full 100-message pages seeding the deep channel, plus one short tail page.
const FULL_PAGES: usize = 50;

fn runtime(mock: &MockRest) -> TicketRuntime {
    let pool = PgPoolOptions::new()
        .connect_lazy("postgres://agent_test@agent-testdb:5432/agent_test")
        .unwrap();
    let rest = ActionExecutor::with_proxy("ticket-test-token".into(), Some(mock.origin())).unwrap();
    let runtime = TicketRuntime::new(
        pool,
        rest,
        TicketConfig {
            guild_id: "100".into(),
            category_id: "200".into(),
            panel_channel_id: "700".into(),
            staff_role_id: "300".into(),
            cooldown_seconds: COOLDOWN_SECONDS,
        },
        std::collections::HashMap::new(),
    )
    .unwrap();
    runtime.set_bot_id(400);
    runtime
}

fn message(id: u64) -> Value {
    json!({
        "id":id.to_string(), "timestamp":two_bot_core::funnel::format_iso_millis(id as i64),
        "author":{"id":"500","username":"member","discriminator":"0"},
        "content":format!("message-{id}"), "attachments":[{"url":format!("https://example.test/{id}")}],
    })
}

/// Page `index` of the deep channel: 100 ids, strictly descending.
fn full_page(index: usize) -> Vec<Value> {
    let top = FULL_PAGES as u64 * 100 + 1 - index as u64 * 100;
    (top - 99..=top).rev().map(message).collect()
}

#[tokio::test]
async fn deep_channel_stops_paging_with_truncation_marker() {
    let mut script: Vec<ScriptedResponse> = (0..FULL_PAGES)
        .map(|index| ScriptedResponse::json(200, json!(full_page(index))))
        .collect();
    script.push(ScriptedResponse::json(200, json!([message(1)])));
    let total_pages = script.len();
    let mock = MockRest::start(script, ScriptedResponse::status(500)).await;
    let (snapshot, truncated) = runtime(&mock)
        .capture_history("600")
        .await
        .ok()
        .expect("capped capture completes");
    assert!(truncated, "capped capture must report truncated");
    let requests = mock.requests();
    let fetches = requests
        .iter()
        .filter(|request| request.path.contains("limit=100"))
        .count();
    assert_eq!(
        requests.len(),
        fetches,
        "capture must only fetch history pages"
    );
    assert!(
        fetches < total_pages,
        "deep channel fetched all {fetches} pages without stopping at a cap"
    );
    assert!(
        snapshot.content.to_lowercase().contains("truncat"),
        "capped capture must carry a truncation marker"
    );
    assert!(
        snapshot.message_count >= 100,
        "capped capture must retain at least one page"
    );
    mock.shutdown().await;
}

#[tokio::test]
async fn small_history_is_byte_identical_within_cap() {
    let first: Vec<_> = (3..=102).rev().map(message).collect();
    let mock = MockRest::start(
        vec![
            ScriptedResponse::json(200, json!(first)),
            ScriptedResponse::json(200, json!([message(2), message(1)])),
        ],
        ScriptedResponse::status(500),
    )
    .await;
    let (snapshot, truncated) = runtime(&mock)
        .capture_history("600")
        .await
        .ok()
        .expect("small capture completes");
    assert!(!truncated, "small capture must report not truncated");
    assert_eq!(snapshot.message_count, 102);
    let expected = (1..=102)
        .map(|id| {
            format!(
                "[{}] member: message-{id} https://example.test/{id}",
                two_bot_core::funnel::format_iso_millis(id)
            )
        })
        .collect::<Vec<_>>()
        .join("\n");
    assert_eq!(snapshot.content, expected);
    assert!(
        !snapshot.content.to_lowercase().contains("truncat"),
        "small capture must not truncate"
    );
    let requests = mock.requests();
    assert_eq!(requests.len(), 2);
    mock.shutdown().await;
}

#[tokio::test]
async fn malformed_page_still_refused_as_invalid_evidence() {
    let first: Vec<_> = (102..=201).rev().map(message).collect();
    let mock = MockRest::start(
        vec![
            ScriptedResponse::json(200, json!(first)),
            ScriptedResponse::json(
                200,
                json!([{"id":"101","content":"missing attachments and timestamp"}]),
            ),
        ],
        ScriptedResponse::status(500),
    )
    .await;
    let result = runtime(&mock).capture_history("600").await;
    assert!(
        matches!(result, Err(Failure::InvalidEvidence)),
        "malformed page must refuse InvalidEvidence"
    );
    let requests = mock.requests();
    assert_eq!(requests.len(), 2);
    mock.shutdown().await;
}
