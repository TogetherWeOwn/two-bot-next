//! Isolated child processes keep boot configuration out of sibling tests.
use super::*;
use serde_json::Value;
use tokio::{
    io::{AsyncReadExt, AsyncWriteExt},
    net::{TcpListener, TcpStream},
    sync::RwLock,
};
use two_bot_core::{Config, Secret};

const PROBE: &str = "RETENTION_BOOT_PROBE";
const PROBE_TEST: &str = "retention_runtime_tests::boot::isolated_boot_probe";

#[test]
fn boot_registers_safe_modes_and_parks_invalid_disabled_or_missing_database() {
    let Ok(url) = std::env::var("TWO_TEST_DATABASE_URL") else {
        assert_ne!(
            std::env::var("GITHUB_ACTIONS").as_deref(),
            Ok("true"),
            "CI must configure retention boot fixtures"
        );
        eprintln!("SKIP retention boot database fixture: TWO_TEST_DATABASE_URL not set");
        return;
    };
    two_bot_testsupport::guard_database_url(&url).expect("guard bootstrap before child process");
    for mode in [
        "missing",
        "dry-run",
        "execute",
        "off",
        "invalid",
        "missing-db",
    ] {
        let mut command = std::process::Command::new(std::env::current_exe().unwrap());
        command
            .env_clear()
            .args([PROBE_TEST, "--exact", "--nocapture"])
            .env(PROBE, mode)
            .env("TWO_TEST_DATABASE_URL", &url)
            .env("TWO_DATABASE_TLS", "local-only");
        if !matches!(mode, "missing" | "missing-db") {
            command.env(crate::retention_jobs::MODE_SETTING, mode);
        }
        let output = command.output().expect("run isolated retention boot probe");
        assert!(
            output.status.success(),
            "boot mode {mode} failed:\n{}\n{}",
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );
        assert!(String::from_utf8_lossy(&output.stdout).contains("running 1 test"));
        assert!(String::from_utf8_lossy(&output.stderr).contains("retention boot probe completed"));
    }
}

async fn readiness(address: std::net::SocketAddr) -> Value {
    let mut socket = TcpStream::connect(address).await.unwrap();
    socket
        .write_all(b"GET /readyz HTTP/1.0\r\nHost: localhost\r\n\r\n")
        .await
        .unwrap();
    let mut response = String::new();
    socket.read_to_string(&mut response).await.unwrap();
    let (_, body) = response
        .split_once("\r\n\r\n")
        .expect("HTTP readiness response");
    serde_json::from_str(body).expect("readiness JSON")
}

#[tokio::test]
async fn isolated_boot_probe() {
    let Ok(mode) = std::env::var(PROBE) else {
        return;
    };
    let db = database::database()
        .await
        .expect("child bootstrap supplied");
    database::seed(db.pool()).await;
    let before = database::snapshot(db.pool()).await;
    // The name is generated by testsupport. No application binding is read.
    let fixture_url = format!("postgres://agent_test:@agent-testdb:5432/{}", db.name());
    two_bot_testsupport::guard_database_url(&fixture_url).unwrap();
    let config = Config {
        discord_token: None,
        database_url: (mode != "missing-db").then(|| Secret::new(fixture_url)),
        guild_id: None,
        listen_addr: "127.0.0.1:0".into(),
    };
    let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
    let address = listener.local_addr().unwrap();
    let (stop, _) = watch::channel(false);
    let gateway = server::SharedState::new(
        Arc::new(RwLock::new(crate::gateway::GatewayState::Unconfigured)),
        None,
    );
    let shutdown = stop.clone();
    let owner = tokio::spawn(async move {
        website_jobs::serve(
            &config,
            listener,
            gateway,
            shutdown,
            None,
            Arc::new(std::sync::OnceLock::new()),
            None,
            None,
            None,
        )
        .await
    });
    let parked = matches!(mode.as_str(), "off" | "invalid" | "missing-db");
    let observed = tokio::time::timeout(Duration::from_secs(30), async {
        loop {
            let response = readiness(address).await;
            let entry = &response["jobs"]["retention"];
            assert!(
                entry.is_object(),
                "retention must be registered in real readiness, even when parked: {response}"
            );
            assert_eq!(entry["parked"], parked);
            if parked || !entry["last_success"].is_null() {
                break entry.clone();
            }
            tokio::task::yield_now().await;
        }
    })
    .await
    .expect("boot must invoke retention within bounded startup jitter");
    if parked {
        assert_eq!(observed["running"], false);
        assert!(observed["last_start"].is_null());
        assert!(observed["last_success"].is_null());
    } else {
        assert!(!observed["last_start"].is_null());
        assert!(!observed["last_success"].is_null());
    }
    stop.send_replace(true);
    tokio::time::timeout(Duration::from_secs(10), owner)
        .await
        .expect("boot owner must join retention shutdown")
        .unwrap()
        .unwrap();
    assert!(
        TcpStream::connect(address).await.is_err(),
        "shutdown closes HTTP owner"
    );
    let after = database::snapshot(db.pool()).await;
    if mode == "execute" {
        assert_ne!(
            after, before,
            "actual boot must invoke destructive work only on the disposable fixture"
        );
        let pending: i64 = sqlx::query_scalar("SELECT count(*) FROM retention_guild_purge_queue")
            .fetch_one(db.pool())
            .await
            .unwrap();
        let complete: i64 = sqlx::query_scalar("SELECT count(*) FROM retention_deletion_requests WHERE status = 'completed' AND receipt_id IS NOT NULL").fetch_one(db.pool()).await.unwrap();
        assert_eq!((pending, complete), (0, 1));
    } else {
        assert_eq!(
            after, before,
            "default/dry/invalid/off/missing-db boot cannot delete"
        );
    }
    db.close().await.unwrap();
    eprintln!("retention boot probe completed");
}
