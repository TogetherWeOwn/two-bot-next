//! Disposable Postgres qualification of the signed receiver's pre-effect boundary.

use super::*;
use futures_util::FutureExt;
use sqlx::{postgres::PgPoolOptions, PgPool};
use std::panic::AssertUnwindSafe;

struct RecordedMutations {
    calls: AtomicUsize,
    executor: EventMutationExecutor,
}

impl EventMutateEffect for RecordedMutations {
    fn execute_mutation<'a>(
        &'a self,
        guild: &'a str,
        call: &'a EventCall,
    ) -> BoxFuture<'a, Result<Value, EventActionError>> {
        self.calls.fetch_add(1, Ordering::SeqCst);
        self.executor.execute_mutation(guild, call)
    }
}

async fn fixture_role(owner: &PgPool, name: &str) -> PgPool {
    // Interpolate only the identifier generated by TestDatabase, not request data.
    assert!(name.starts_with("two_bot_test_") && name.len() <= 63);
    assert!(name.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_'));
    sqlx::raw_sql(sqlx::AssertSqlSafe(format!(
        "CREATE ROLE {name} LOGIN NOINHERIT;
         GRANT USAGE ON SCHEMA public TO {name};
         GRANT SELECT, INSERT, UPDATE ON internal_nonces, internal_clock_high_water,
           internal_idempotency, internal_event_keys, scheduled_events, event_instance_windows TO {name};
         GRANT SELECT, INSERT ON internal_action_log TO {name};
         GRANT SELECT ON event_voice_channels, scheduled_events_tombstone, scheduled_events_claim TO {name};
         GRANT USAGE ON SEQUENCE internal_idempotency_intent_id_seq, internal_action_log_audit_id_seq TO {name};"
    )))
    .execute(owner)
    .await
    .unwrap();
    let runtime = PgPoolOptions::new()
        .max_connections(1)
        .acquire_timeout(Duration::from_secs(5))
        .connect_with(
            owner
                .connect_options()
                .as_ref()
                .clone()
                .username(name)
                .options([("statement_timeout", "5000ms"), ("lock_timeout", "2000ms")]),
        )
        .await
        .unwrap();
    assert!(sqlx::query_scalar::<_, bool>(
        "SELECT current_user = $1 AND session_user = $1 AND NOT r.rolsuper AND NOT r.rolcreaterole
           AND NOT r.rolbypassrls AND NOT pg_has_role(c.relowner, 'MEMBER')
           AND NOT has_table_privilege(c.oid, 'TRIGGER')
         FROM pg_roles r, pg_class c
         WHERE r.rolname = current_user AND c.oid = 'internal_idempotency'::regclass"
    )
    .bind(name)
    .fetch_one(&runtime)
    .await
    .unwrap());
    runtime
}

async fn install_denial(owner: &PgPool) {
    // AFTER INSERT leaves ON CONFLICT DO NOTHING available for readback;
    // the UPDATE guard rejects only a transition that gives execution authority.
    sqlx::raw_sql(
        "CREATE FUNCTION fixture_deny_claim() RETURNS trigger LANGUAGE plpgsql AS $$
           BEGIN RAISE EXCEPTION 'fixture denies new event claim' USING ERRCODE = '42501'; END;
         $$;
         CREATE TRIGGER fixture_deny_insert AFTER INSERT ON internal_idempotency
           FOR EACH ROW WHEN (NEW.action IN ('event.upsert', 'event.cancel'))
           EXECUTE FUNCTION fixture_deny_claim();
         CREATE TRIGGER fixture_deny_reacquire AFTER UPDATE ON internal_idempotency
           FOR EACH ROW WHEN (NEW.action IN ('event.upsert', 'event.cancel')
                              AND OLD.state = 'not_sent' AND NEW.state = 'in_flight')
           EXECUTE FUNCTION fixture_deny_claim();",
    )
    .execute(owner)
    .await
    .unwrap();
}

async fn event_snapshot(observer: &PgPool) -> Value {
    // Nonce/clock writes commit before claim; sequence values may advance on
    // rolled-back inserts. Neither is durable execution authority or a receipt.
    sqlx::query_scalar(
        "SELECT jsonb_build_array(
           (SELECT jsonb_agg(to_jsonb(i) ORDER BY intent_id) FROM internal_idempotency i
              WHERE action IN ('event.upsert', 'event.cancel')),
           (SELECT jsonb_agg(to_jsonb(a) ORDER BY audit_id) FROM internal_action_log a
              WHERE action IN ('event.upsert', 'event.cancel')),
           (SELECT jsonb_agg(to_jsonb(k) ORDER BY guild_id, event_key) FROM internal_event_keys k),
           (SELECT jsonb_agg(to_jsonb(e) ORDER BY guild_id, event_id) FROM scheduled_events e),
           (SELECT jsonb_agg(to_jsonb(w) ORDER BY guild_id, event_id, instance_starts_at)
              FROM event_instance_windows w))",
    )
    .fetch_one(observer)
    .await
    .unwrap()
}

async fn seed_claim(
    store: &InternalActionStore,
    raw: &str,
    intent: &str,
    target: Option<&str>,
) -> ExecutionClaim {
    let identity =
        RequestIdentity::new("website-staging", intent, "event.upsert", raw.as_bytes()).unwrap();
    let subject = AuditSubject {
        guild_id: Some(DiscordId::new(staging_guild()).unwrap()),
        target_id: target.map(|id| DiscordId::new(id).unwrap()),
        ..AuditSubject::default()
    };
    let InternalClaim::Claimed(claim) = store.claim(&identity, &subject).await.unwrap() else {
        panic!("seed intent must be new");
    };
    claim
}

async fn send(app: &Router, raw: &str, intent: &str) -> (StatusCode, HeaderMap, Value) {
    tokio::time::timeout(
        REQUEST_TIMEOUT + Duration::from_secs(1),
        answer(app.clone(), signed(raw, "old", intent)),
    )
    .await
    .expect("receiver exceeded its request deadline")
}

fn assert_refusal(
    reply: (StatusCode, HeaderMap, Value),
    expected: StatusCode,
    code: &str,
    retryable: bool,
) {
    let (status, headers, body) = reply;
    assert_eq!(status, expected, "{body}");
    assert_eq!(headers[header::CACHE_CONTROL], "no-store");
    assert!(!headers.contains_key(header::RETRY_AFTER));
    assert!(!headers.contains_key("idempotent-replay"));
    assert!(body["request_id"].as_str().is_some_and(|id| !id.is_empty()));
    assert_eq!(
        body,
        json!({"ok": false, "request_id": body["request_id"], "error": {
            "code": code, "message": "Internal action refused", "retryable": retryable
        }})
    );
}

async fn exercise(owner: PgPool, runtime: PgPool, guarded: bool) {
    let fresh = upsert_payload("fresh");
    let known = upsert_payload("known");
    let unknown = upsert_payload("unknown");
    let api = MockEventApi::start_scripted(
        [READ_EVENT_ID, CREATE_EVENT_ID, READ_EVENT_ID]
            .into_iter()
            .map(|id| ScriptedEvent {
                status: StatusCode::OK,
                body: discord_event_for(id, 1),
            })
            .collect(),
    )
    .await;
    let guard = two_bot_discord::ratelimit_guard::RateLimitGuard::new(Default::default()).unwrap();
    let executor = ActionExecutor::with_proxy_and_guard(
        "not-a-credential".to_owned(),
        Some(api.origin.clone()),
        Arc::new(guard),
    )
    .unwrap();
    let events = Arc::new(RecordedMutations {
        calls: AtomicUsize::new(0),
        executor: EventMutationExecutor::new(executor, runtime.clone()),
    });
    let announcements = Arc::new(MockEffect::new(MockOutcome::Success));
    let app = router(Arc::new(ReceiverState::new(
        config(),
        runtime.clone(),
        announcements.clone(),
        announcements.clone(),
        Arc::new(MockEventRead::default()),
        events.clone(),
        Arc::new(MockModeration::default()),
        Arc::new(MockChannel::default()),
    )));
    let (status, _, completed) = send(&app, &known, "intent-completed").await;
    assert_eq!(status, StatusCode::OK, "{completed}");
    assert_eq!(
        completed["result"],
        json!({"outcome": "created", "event_id": READ_EVENT_ID})
    );
    let store = InternalActionStore::new(runtime);
    let released = seed_claim(&store, &known, "intent-released", Some(READ_EVENT_ID)).await;
    store.release_proven_not_sent(released).await.unwrap();
    let uncertain = seed_claim(&store, &unknown, "intent-unknown", None).await;
    store.mark_unknown(&uncertain).await.unwrap();
    let initial = event_snapshot(&owner).await;
    assert_eq!(initial[0][0]["state"], "completed");
    assert_eq!(initial[0][1]["state"], "not_sent");
    assert_eq!(initial[0][2]["state"], "unknown");
    assert_eq!(initial[0].as_array().unwrap().len(), 3);
    assert_eq!(events.calls.load(Ordering::SeqCst), 1);
    assert_eq!(api.count(), 1);
    if guarded {
        install_denial(&owner).await;
    }

    for (index, (raw, intent, outcome, id)) in [
        (&fresh, "intent-fresh", "created", CREATE_EVENT_ID),
        (&known, "intent-released", "updated", READ_EVENT_ID),
    ]
    .into_iter()
    .enumerate()
    {
        let reply = send(&app, raw, intent).await;
        let expected_calls = if guarded { 1 } else { index + 2 };
        assert_eq!(
            events.calls.load(Ordering::SeqCst),
            expected_calls,
            "{intent}"
        );
        assert_eq!(api.count(), expected_calls, "{intent}");
        if guarded {
            assert_refusal(reply, StatusCode::INTERNAL_SERVER_ERROR, "internal", true);
            assert_eq!(event_snapshot(&owner).await, initial, "{intent}");
        } else {
            let (status, headers, body) = reply;
            assert_eq!(status, StatusCode::OK, "{intent}: {body}");
            assert!(!headers.contains_key("idempotent-replay"), "{intent}");
            assert_eq!(body["result"], json!({"outcome": outcome, "event_id": id}));
        }
    }

    let post_claim = event_snapshot(&owner).await;
    let event_calls = events.calls.load(Ordering::SeqCst);
    if !guarded {
        assert_eq!(post_claim[0][1]["intent_id"], initial[0][1]["intent_id"]);
        assert_eq!(post_claim[0][1]["state"], "completed");
        assert_eq!(post_claim[0][3]["state"], "completed");
    }
    let (status, headers, replay) = send(&app, &known, "intent-completed").await;
    assert_eq!(status, StatusCode::OK, "{replay}");
    assert_eq!(headers["idempotent-replay"], "true");
    assert_eq!(replay["result"], completed["result"]);
    assert_refusal(
        send(&app, &unknown, "intent-unknown").await,
        StatusCode::CONFLICT,
        "needs_reconciliation",
        false,
    );
    assert_eq!(events.calls.load(Ordering::SeqCst), event_calls);
    assert_eq!(api.count(), event_calls);
    assert_eq!(event_snapshot(&owner).await, post_claim);

    let (status, headers, posted) = send(&app, payload(), "intent-announcement").await;
    assert_eq!(status, StatusCode::OK, "{posted}");
    assert!(!headers.contains_key("idempotent-replay"));
    let (status, headers, replay) = send(&app, payload(), "intent-announcement").await;
    assert_eq!(status, StatusCode::OK, "{replay}");
    assert_eq!(headers["idempotent-replay"], "true");
    assert_eq!(replay["result"], posted["result"]);
    assert_eq!(announcements.calls(), 1);
    assert_eq!(events.calls.load(Ordering::SeqCst), event_calls);
    assert_eq!(api.count(), event_calls);
    assert_eq!(event_snapshot(&owner).await, post_claim);
    let burned: i64 = sqlx::query_scalar("SELECT count(*) FROM internal_nonces")
        .fetch_one(&owner)
        .await
        .unwrap();
    assert_eq!(burned, 7, "every request passed the durable nonce gate");
}

#[tokio::test]
async fn event_claim_denial_stops_signed_receiver_before_effect() {
    for guarded in [false, true] {
        let Some(db) = database().await else { return };
        let owner = db.pool();
        let name = db.name();
        let runtime = fixture_role(owner, name).await;
        // Clean up the global fixture role even on an assertion failure.
        let result = AssertUnwindSafe(exercise(owner.clone(), runtime.clone(), guarded))
            .catch_unwind()
            .await;
        runtime.close().await;
        // This is the same generated identifier validated by fixture_role.
        let drop_role = sqlx::raw_sql(sqlx::AssertSqlSafe(format!(
            "DROP OWNED BY {name}; DROP ROLE {name};"
        )))
        .execute(owner)
        .await;
        db.close().await.unwrap();
        drop_role.unwrap();
        result.unwrap();
    }
}
