/// Catalog keys with an implemented boot-time process-environment read
/// (`StickyRuntime::from_env` gates and gateway intents). Every other
/// storable key's value has no runtime consumer: a database-only setting
/// stays inert after restart, and onboarding/automod/scorecard/classifier
/// loaders below supply defaults without being called during boot.
const BOOT_ENV: &[&str] = &[
    "TWO_AUTOMATIONS",
    "TWO_ANNOUNCEMENTS",
    "TWO_TEXT_COMMANDS",
    "TWO_FEED_POLL_SECONDS",
    "TWO_AUTOMOD",
    "DISCORD_TICKET_CATEGORY_ID",
    "DISCORD_TICKET_STAFF_ROLE_ID",
    "DISCORD_TICKET_PANEL_CHANNEL_ID",
];

fn repository_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn markdown_cell(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('|', "&#124;")
        .replace('`', "&#96;")
        .replace(['\r', '\n'], " ")
}

fn json_cell(value: &Value) -> String {
    format!("`{}`", markdown_cell(&value.to_string()))
}

fn permissions(command: &CommandDefinition) -> String {
    let Some(raw) = &command.default_member_permissions else {
        return "Everyone (no default permission gate)".to_owned();
    };
    let bits: u64 = raw.parse().expect("decimal permission bitfield");
    let mut remaining = bits;
    let mut names = Vec::new();
    for (flag, name) in [
        (PERM_KICK_MEMBERS, "KickMembers"),
        (PERM_BAN_MEMBERS, "BanMembers"),
        (PERM_MANAGE_CHANNELS, "ManageChannels"),
        (PERM_MANAGE_GUILD, "ManageGuild"),
        (PERM_MANAGE_MESSAGES, "ManageMessages"),
        (PERM_MANAGE_EVENTS, "ManageEvents"),
        (PERM_MODERATE_MEMBERS, "ModerateMembers"),
    ] {
        if bits & flag != 0 {
            names.push(name.to_owned());
            remaining &= !flag;
        }
    }
    if remaining != 0 {
        names.push(format!("unmapped bits {remaining}"));
    }
    format!("{} (`{raw}`)", names.join(" + "))
}

fn render_commands() -> String {
    let mut commands = InteractionRouter::new(RouterGates {
        configured_guild: None,
        scorecard: true,
        automations: true,
        announcements: true,
        moderation: true,
        voice: true,
        voice_assistant: true,
        tickets: true,
        self_roles: true,
        onboarding_picker: true,
        session_picker: true,
    })
    .publish_set(&[])
    .expect("compiled built-in registry");
    commands.sort_by(|a, b| a.name.cmp(&b.name));
    let mut output = COMMAND_INTRO.to_owned();
    writeln!(output, "Built-in commands: {}.\n", commands.len()).unwrap();
    for command in commands {
        writeln!(output, "## `/{}`", command.name).unwrap();
        writeln!(output, "\n{}\n", markdown_cell(&command.description)).unwrap();
        writeln!(output, "- Default permissions: {}", permissions(&command)).unwrap();
        writeln!(output, "- Available in DMs: {}\n", command.dm_permission).unwrap();
        if command.options.is_empty() {
            output.push_str("No options.\n\n");
            continue;
        }
        output.push_str(
            "| Option | Type | Required | Min | Max | Max length | Choices | Description |\n\
                         | --- | --- | --- | --- | --- | --- | --- | --- |\n",
        );
        for option in command.options {
            let kind = match option.kind {
                n if n == CommandOptionType::String.as_u8() => "string",
                n if n == CommandOptionType::Integer.as_u8() => "integer",
                n if n == CommandOptionType::Boolean.as_u8() => "boolean",
                n if n == CommandOptionType::User.as_u8() => "user",
                n if n == CommandOptionType::Channel.as_u8() => "channel",
                n if n == CommandOptionType::Role.as_u8() => "role",
                n if n == CommandOptionType::Attachment.as_u8() => "attachment",
                n => panic!("document new command option type {n}"),
            };
            let choices = if option.choices.is_empty() {
                "—".to_owned()
            } else {
                option
                    .choices
                    .iter()
                    .map(|choice| {
                        format!(
                            "{} = {}",
                            markdown_cell(&choice.name),
                            json_cell(&json!(choice.value))
                        )
                    })
                    .collect::<Vec<_>>()
                    .join("; ")
            };
            writeln!(
                output,
                "| `{}` | {kind} | {} | {} | {} | {} | {choices} | {} |",
                markdown_cell(&option.name),
                option.required.unwrap_or(false),
                option.min_value.map_or("—".to_owned(), |v| v.to_string()),
                option.max_value.map_or("—".to_owned(), |v| v.to_string()),
                option.max_length.map_or("—".to_owned(), |v| v.to_string()),
                markdown_cell(&option.description),
            )
            .unwrap();
        }
        output.push('\n');
    }
    output.trim_end_matches('\n').to_owned() + "\n"
}

