fn render_configuration() -> String {
    let descriptions: BTreeMap<String, String> =
        serde_json::from_str(include_str!("fixtures/reference_settings.json")).unwrap();
    let keys: BTreeSet<_> = SETTING_CLASSES.iter().map(|(key, _)| *key).collect();
    assert_eq!(keys.len(), SETTING_CLASSES.len(), "duplicate catalog key");
    assert_eq!(
        keys,
        descriptions.keys().map(String::as_str).collect(),
        "update the settings description supplement with the catalog"
    );
    let defaults = setting_defaults();
    assert!(defaults.keys().all(|key| keys.contains(key)));
    let mut settings = SETTING_CLASSES.to_vec();
    settings.sort_by_key(|(key, _)| *key);
    let mut output = CONFIG_INTRO.to_owned();
    writeln!(output, "Catalog entries: {}.\n", settings.len()).unwrap();
    output.push_str(
        "| Key | Class | Parsed default | Application | Description |\n\
                     | --- | --- | --- | --- | --- |\n",
    );
    for (key, class) in settings {
        let boot_read = BOOT_ENV.contains(&key);
        let hot_wired = HOT_WIRED.contains(&key);
        let (class, application) = match class {
            SettingClass::EnvOnly => ("env_only", "environment only"),
            SettingClass::Cold if boot_read => ("cold", "env at boot; stored unwired"),
            SettingClass::Cold => ("cold", "stored unwired"),
            SettingClass::Hot if hot_wired => ("hot", "stored unwired (reload-report hot)"),
            SettingClass::Hot if boot_read => ("hot", "env at boot; stored unwired"),
            SettingClass::Hot => ("hot", "stored unwired"),
        };
        let default = if is_secret_key(key) {
            "Not rendered (secret)".to_owned()
        } else {
            defaults
                .get(key)
                .map_or_else(|| "Not specified in Next".to_owned(), json_cell)
        };
        let description = &descriptions[key];
        assert!(!description.trim().is_empty(), "description for {key}");
        writeln!(
            output,
            "| `{key}` | {class} | {default} | {application} | {} |",
            markdown_cell(description)
        )
        .unwrap();
    }
    output
}

fn is_secret_key(key: &str) -> bool {
    [
        "TOKEN",
        "SECRET",
        "DATABASE_URL",
        "ACCESS_KEY",
        "PSEUDONYM_KEY",
    ]
    .iter()
    .any(|marker| key.contains(marker))
}

fn generated_documents() -> [(&'static str, String); 2] {
    [
        ("docs/commands.md", render_commands()),
        ("docs/configuration.md", render_configuration()),
    ]
}

fn check_document(path: &str, committed: &str, generated: &str) -> Result<(), String> {
    if committed == generated {
        Ok(())
    } else {
        Err(format!(
            "{path} is stale; regenerate with: python3 scripts/cargo_cache.py run -- test \
             -p two-bot-core --test reference_docs regenerate_reference_docs -- --ignored"
        ))
    }
}

#[test]
fn committed_references_match_compiled_metadata() {
    for (path, generated) in generated_documents() {
        let committed = std::fs::read_to_string(repository_root().join(path)).unwrap();
        assert_eq!(
            committed,
            generated,
            "{}",
            check_document(path, &committed, &generated)
                .err()
                .unwrap_or_default()
        );
    }
}

#[test]
fn rejects_deliberately_stale_documents() {
    for (path, generated) in generated_documents() {
        let stale = format!("{generated}\nDeliberately stale fixture.\n");
        let error = check_document(path, &stale, &generated).unwrap_err();
        assert!(error.contains(path));
        assert!(error.contains("regenerate_reference_docs"));
        assert!(check_document(path, &generated, &generated).is_ok());
    }
}

#[test]
fn boot_env_keys_are_catalogued_storable_keys() {
    let keys: BTreeSet<_> = SETTING_CLASSES.iter().map(|(key, _)| *key).collect();
    for key in BOOT_ENV {
        assert!(keys.contains(key), "{key} is not a catalog key");
        assert!(
            matches!(
                classify_key(key),
                Some(SettingClass::Cold | SettingClass::Hot)
            ),
            "{key} is env-only; its row never consults BOOT_ENV"
        );
    }
}

#[test]
fn references_contain_no_snowflakes_or_secret_defaults() {
    let snowflake = regex::Regex::new(r"\b[0-9]{17,20}\b").unwrap();
    for (_, document) in generated_documents() {
        assert!(
            !snowflake.is_match(&document),
            "references must not embed live IDs"
        );
    }
    let defaults = setting_defaults();
    assert!(defaults.keys().all(|key| !is_secret_key(key)));
}

#[test]
fn escapes_markdown_metadata() {
    assert_eq!(
        markdown_cell("a|b\n<value> & `code`"),
        "a&#124;b &lt;value&gt; &amp; &#96;code&#96;"
    );
}

#[test]
#[ignore = "explicitly regenerate committed docs; never update during normal tests"]
fn regenerate_reference_docs() {
    for (path, generated) in generated_documents() {
        std::fs::write(repository_root().join(path), generated).unwrap();
    }
}
