// Acceptance tests (protected): the promotion-gate scrape intake is byte-bounded.
//
// Contract under test: `fetchExposition` (`./promotion-error-gate.mjs`)
// bounds its `/ops/metrics` intake at 64 KiB, like every sibling reader
// (the Worker scrape and MCP container reads):
// - an exposition of exactly 65536 bytes is admitted and judges exactly
//   like its unpadded self (same firing, REST delta and sample count),
//   with or without a `content-length` header;
// - an exposition of 65537 bytes fails closed through the existing
//   scrape-failed refusal, with or without a `content-length` header;
// - every scrape is bounded, not just the first: an over-cap second
//   scrape fails the gate even when the baseline scrape was small.
//
// These tests were written test-first against a baseline where the reader
// buffers the body unbounded (`await response.text()` with no cap). The
// over-cap tests are expected to FAIL there (the gate resolves instead of
// rejecting) and PASS once the reader refuses over-cap bodies before or
// while reading. Every over-cap fixture is Worker-valid on its own
// (`parseAlertScrape` accepts it), so a rejection pins the byte cap, not
// the parser. Do not edit this file to make an implementation pass; fix
// the implementation. Any fix shape is accepted: a `content-length`
// precheck, an incremental streaming cap, or a post-read byte-length
// check, alone or combined, as long as exactly-64 KiB passes and
// 64 KiB + 1 byte fails closed with the existing scrape-failed refusal.
//
// Offline only: stub `fetch` implementations serve real `Response`
// objects with synthetic in-memory bodies. No network, database,
// deployed Worker or secret is contacted.
// Run from wrangler/: node --test scripts/test-promotion-gate-intake-cap.mjs
import assert from 'node:assert/strict';
import test from 'node:test';
import { runLiveGate } from './promotion-error-gate.mjs';
import { parseAlertScrape } from '../src/metrics-scrape.ts';
import { metricsLines } from '../test/fixtures/metrics.ts';

const CAP = 64 * 1024;
const TOKEN = 'x'.repeat(40);

/** Join fixture lines into one exposition; every line is ASCII. */
function exposition(lines) {
  return `${lines.join('\n')}\n`;
}

function baseExposition() {
  return exposition(metricsLines());
}

/** Full valid exposition with the `other` REST route counters overridden. */
function burstExposition(twoXx, fiveXx) {
  return exposition(metricsLines().map((line) => {
    if (line === 'two_bot_rest_requests_total{route="other",result="2xx"} 0') {
      return `two_bot_rest_requests_total{route="other",result="2xx"} ${twoXx}`;
    }
    if (line === 'two_bot_rest_requests_total{route="other",result="5xx"} 0') {
      return `two_bot_rest_requests_total{route="other",result="5xx"} ${fiveXx}`;
    }
    return line;
  }));
}

/**
 * Pad a valid exposition with one trailing `#` comment line so the result
 * is exactly `size` bytes. Comment lines never reach the parser, so the
 * padded body stays Worker-valid. ASCII only: bytes equal characters.
 */
function padTo(text, size) {
  const current = Buffer.byteLength(text, 'utf8');
  assert.ok(current < size - 2, `fixture ${current} bytes already fills ${size}`);
  const padded = `${text}#${'x'.repeat(size - current - 2)}\n`;
  assert.equal(Buffer.byteLength(padded, 'utf8'), size);
  assert.ok(parseAlertScrape(padded), 'padded fixture must stay Worker-valid');
  return padded;
}

/**
 * Stub fetch serving each body as a real `Response`, in order, repeating
 * the last. Real responses keep every fix shape honest: `response.text()`,
 * `response.headers` and `response.body` all behave like the network.
 */
function stubFetch(bodies, { contentLength = false } = {}) {
  let calls = 0;
  const fetchImpl = async () => {
    calls += 1;
    const body = bodies[Math.min(calls - 1, bodies.length - 1)];
    const headers = contentLength ? { 'content-length': String(Buffer.byteLength(body, 'utf8')) } : {};
    return new Response(body, { status: 200, headers });
  };
  return { fetchImpl, calls: () => calls };
}

function gate(fetchImpl) {
  return runLiveGate({
    metricsUrl: 'https://staging.example',
    token: TOKEN,
    sampleIntervalSeconds: 75,
    fetchImpl,
    sleep: async () => {},
    nowSeconds: () => 1_000_000,
    retrySleepSeconds: 0,
  });
}

test('exact-64 KiB exposition passes with verdicts unchanged', async () => {
  const base = baseExposition();
  const exact = padTo(base, CAP);
  const [plain, capped] = await Promise.all([
    gate(stubFetch([base]).fetchImpl),
    gate(stubFetch([exact]).fetchImpl),
  ]);
  assert.deepEqual(
    { firing: capped.firing, restDelta: capped.restDelta, sampleCount: capped.sampleCount },
    { firing: plain.firing, restDelta: plain.restDelta, sampleCount: plain.sampleCount },
  );
  assert.deepEqual(capped.firing, []);
  assert.equal(capped.restDelta, 0);
});

test('exact-64 KiB exposition with content-length passes', async () => {
  const exact = padTo(baseExposition(), CAP);
  const { fetchImpl, calls } = stubFetch([exact], { contentLength: true });
  const verdict = await gate(fetchImpl);
  assert.deepEqual(verdict.firing, []);
  assert.equal(verdict.restDelta, 0);
  assert.ok(calls() >= 2, 'both scrapes run');
});

test('exact-64 KiB burst still fails the gate', async () => {
  const first = padTo(burstExposition(100, 0), CAP);
  const second = padTo(burstExposition(180, 20), CAP);
  const verdict = await gate(stubFetch([first, second]).fetchImpl);
  assert.deepEqual(verdict.firing, ['rest_5xx_rate']);
  assert.equal(verdict.restDelta, 100);
});

test('over-cap exposition fails closed without content-length', async () => {
  const over = padTo(baseExposition(), CAP + 1);
  const { fetchImpl, calls } = stubFetch([over]);
  await assert.rejects(gate(fetchImpl), /metrics scrape failed/);
  assert.ok(calls() >= 1, 'the bounded read rejects the fetched body');
});

test('over-cap exposition with content-length fails closed', async () => {
  const over = padTo(baseExposition(), CAP + 1);
  const { fetchImpl, calls } = stubFetch([over], { contentLength: true });
  await assert.rejects(gate(fetchImpl), /metrics scrape failed/);
  assert.ok(calls() >= 1, 'the bounded read rejects the fetched body');
});

test('over-cap second scrape fails closed after a small baseline', async () => {
  const over = padTo(baseExposition(), CAP + 1);
  const { fetchImpl } = stubFetch([baseExposition(), over]);
  await assert.rejects(gate(fetchImpl), /metrics scrape failed/);
});
