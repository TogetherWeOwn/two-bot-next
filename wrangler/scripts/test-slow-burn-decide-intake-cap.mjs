// Acceptance tests (protected): the slow-burn decide driver bounds its exposition read.
//
// Contract under test: `slow-burn-decide.mjs` reads its `--exposition`
// file through a 64 KiB bounded read, matching the ring's existing
// 1 MiB bounded load:
// - an exposition of exactly 65536 bytes decides exactly like its
//   unpadded self (same slow/fast/held/slowCovered verdict and ring);
// - an exposition of 65537 bytes holds: the driver prints the refused
//   verdict (`held: true`, no fire, no coverage, caller's ring
//   untouched) and exits 0, exactly like a Worker-refused scrape.
//
// These tests were written test-first against a baseline where the
// driver reads the exposition unbounded (`readFileSync` with no cap,
// beside the ring's capped load). The over-cap tests are expected to
// FAIL there (the driver decides instead of holding) and PASS once the
// exposition goes through the bounded-read helper. Every fixture is
// Worker-valid on its own (`parseAlertScrape` accepts it), so a hold
// pins the byte cap, not the parser. Do not edit this file to make an
// implementation pass; fix the implementation.
//
// Offline only: synthetic exposition and ring files under a scratch
// directory, driver subprocesses with a hermetic environment. No
// network, database, deployed Worker or secret is contacted.
// Run from wrangler/: node --test scripts/test-slow-burn-decide-intake-cap.mjs
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import test from 'node:test';
import { parseAlertScrape } from '../src/metrics-scrape.ts';
import { metricsLines } from '../test/fixtures/metrics.ts';

const CAP = 64 * 1024;
const DRIVER = fileURLToPath(new URL('./slow-burn-decide.mjs', import.meta.url));
const NOW = 1_700_000_000;

function inputs(burning) {
  // 25 joins / 300 s, one slow join when burning: 8x the 0.5% budget,
  // above the existing slow threshold and below the fast threshold.
  const ring = Array.from({ length: 84 }, (_, i) => ({
    t: NOW - (84 - i) * 300,
    received: (i + 1) * 25,
    duplicate: 0,
    fastMoves: (i + 1) * (burning ? 24 : 25),
  }));
  const lines = metricsLines().map((line) => {
    if (line.startsWith('two_bot_voice_joins_received_total ')) return 'two_bot_voice_joins_received_total 2125';
    if (line.startsWith('two_bot_voice_join_to_move_seconds_bucket{')) {
      return line.replace(/ 0$/, ` ${85 * (burning ? 24 : 25)}`);
    }
    return line;
  });
  return { ring, text: `${lines.join('\n')}\n` };
}

/**
 * Pad a valid exposition with one trailing `#` comment line so the result
 * is exactly `size` bytes. Comment lines never reach the parser, so the
 * padded body stays Worker-valid. ASCII only: bytes equal characters.
 */
function padTo(text, size) {
  const current = Buffer.byteLength(text, 'utf8');
  assert.ok(current < size - 2, `fixture ${current} bytes already fills ${size}`);
  const padded = `${text}#${'x'.repeat(size - current - 2)}\n`;
  assert.equal(Buffer.byteLength(padded, 'utf8'), size);
  assert.ok(parseAlertScrape(padded), 'padded fixture must stay Worker-valid');
  return padded;
}

function decide(text, ring) {
  const dir = mkdtempSync(join(process.env.PAPERCLIP_RUN_SCRATCH_DIR ?? tmpdir(), 'slow-burn-decide-cap-test-'));
  try {
    const exposition = join(dir, 'metrics.prom');
    const cache = join(dir, 'ring.json');
    writeFileSync(exposition, text);
    const previous = `${JSON.stringify(ring)}\n`;
    writeFileSync(cache, previous);
    const child = spawnSync(process.execPath, [DRIVER, '--exposition', exposition, '--ring', cache, '--now', String(NOW)], {
      encoding: 'utf8', timeout: 10_000, maxBuffer: 1024 * 1024,
      env: { PATH: process.env.PATH ?? '' },
    });
    assert.ifError(child.error);
    assert.equal(child.status, 0, child.stderr);
    assert.equal(child.stderr, '');
    assert.equal(readFileSync(cache, 'utf8'), previous, 'the driver must not overwrite its caller cache');
    return JSON.parse(child.stdout);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

for (const burning of [true, false]) {
  const mode = burning ? 'fire' : 'clear';
  test(`exact-64 KiB exposition preserves covered ${mode} semantics`, () => {
    const { text, ring } = inputs(burning);
    assert.ok(parseAlertScrape(text), 'positive fixture must be Worker-valid');
    const verdict = decide(padTo(text, CAP), ring);
    assert.deepEqual(verdict, decide(text, ring), 'a cap-sized read must judge exactly like the same body unpadded');
    assert.equal(verdict.held, false);
    assert.equal(verdict.slow, burning);
    assert.equal(verdict.fast, false);
    assert.equal(verdict.slowCovered, true);
  });

  test(`over-cap exposition holds instead of a covered ${mode} decision`, () => {
    const { text, ring } = inputs(burning);
    const verdict = decide(padTo(text, CAP + 1), ring);
    assert.equal(verdict.held, true, 'an over-cap exposition must not decide');
    assert.equal(verdict.slow, false);
    assert.equal(verdict.fast, false);
    assert.equal(verdict.slowCovered, false);
    assert.deepEqual(verdict.ring, ring, 'a refused scrape must not advance or prune history');
  });
}
