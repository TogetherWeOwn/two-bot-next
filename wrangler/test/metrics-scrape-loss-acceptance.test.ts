/**
 * Acceptance tests (protected): sustained loss of the metrics scrape is reported.
 *
 * Contract under test: the private keepalive metrics scrape is the observer
 * for every metric-rule alert, so its own sustained loss must be observable
 * even while readiness stays healthy. The keepalive tick persists a bounded
 * scrape-loss streak independently of metric-rule state:
 *
 * - one failed scheduled scrape stays quiet;
 * - three consecutive failed scheduled scrapes emit exactly one ticket
 *   transition whose content contains `ALERT metrics_scrape_lost (ticket)`
 *   and a runbook deep link ending `runbook.md#alert-metrics-scrape-lost`;
 * - timeout, non-OK, oversized and invalid exposition all count as failure,
 *   without echoing response bodies into logs or notifications;
 * - repeated failures after firing emit no duplicate transition, and the
 *   transition is attempted at most once even when the webhook fails
 *   (persist-before-notify, as for metric-rule transitions);
 * - the streak and the firing incident survive Durable Object
 *   reconstruction (they live in DO storage, not in memory);
 * - the first complete valid scrape after a firing loss incident emits
 *   exactly one `RESOLVED metrics_scrape_lost` transition and clears only
 *   scrape-loss state; a valid scrape before firing silently resets the
 *   streak with no RESOLVED;
 * - failed scrapes never resolve (or otherwise clear) a previously firing
 *   metric-rule incident, and scrape-loss recovery does not resolve one
 *   either; metric-rule evaluation on valid scrapes is unchanged;
 * - the existing forwarding switch applies: with forwarding off the
 *   transitions are still persisted and logged as `metrics_alert` events,
 *   but no webhook is posted;
 * - docs/runbook.md gains an `Alert: metrics scrape lost` section stating
 *   the exact 3-consecutive-failures threshold, diagnostic read paths and
 *   the honest missing-evidence behavior (a lost scrape resolves nothing).
 *
 * These tests were written test-first against a baseline where a failed
 * scrape only logged `two-bot metrics scrape failed` and returned, so a
 * healthy readyz could conceal indefinite loss of all metric-based
 * detection. The scrape-loss tests are expected to FAIL there and PASS once
 * the streak is persisted and reported. Do not edit this file to make an
 * implementation pass; fix the implementation.
 *
 * Runtime storage is in-memory; all env values are synthetic. No Discord,
 * database, deployed Worker, Docker daemon or secret bindings are
 * contacted. The production 6000 ms scrape deadline is shrunk to 30 ms so
 * stalled transports settle quickly.
 * Run: node --import ./test/cloudflare-loader.mjs --test test/metrics-scrape-loss-acceptance.test.ts
 */
