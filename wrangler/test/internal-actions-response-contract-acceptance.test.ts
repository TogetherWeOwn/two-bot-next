function chunked(chunks: Uint8Array[], onCancel: () => unknown = () => {}) {
  let pulls = 0;
  const stream = new ReadableStream<Uint8Array>({
    pull(controller) {
      const chunk = chunks[pulls++];
      if (chunk) controller.enqueue(chunk);
      else controller.close();
    },
    cancel: onCancel,
  }, { highWaterMark: 0 });
  return { stream, pulls: () => pulls };
}

test("over-cap body cancels incrementally without draining its tail", async (t) => {
  const logs = captureLogs(t);
  const first = encoder.encode(JSON.stringify(SUCCESSES[0]!.value).padEnd(MAX_RESPONSE_BYTES, " "));
  let cancelled = 0;
  const input = chunked([first, encoder.encode("x"), encoder.encode(PRIVATE)], () => {
    cancelled++;
    return new Promise<void>(() => {});
  });
  const response = await within(relayReceiverResponse(new Response(input.stream, {
    headers: { "content-type": "application/json" },
  }), REQUEST_ID));
  await assertUnavailable(response, logs);
  assert.equal(input.pulls(), 2, "no tail read after crossing the byte cap");
  assert.equal(cancelled, 1, "cancellation is attempted but its never-settling promise is not awaited");
});

