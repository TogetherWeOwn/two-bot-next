function rustMessage(code: string): string {
  return code === "unauthorized" ? "Signature verification failed" : "Internal action refused";
}

/** The receiver's wire failure for a known code, with its real fixed message. */
function wireFailure(code: string, retryable: boolean, requestId = REQUEST_ID) {
  return {
    ok: false, request_id: requestId,
    error: { code, message: rustMessage(code), retryable },
  };
}

/** The relayed projection: same code/status/retryability, fixed message. */
function projectedFailure(code: string, retryable: boolean, requestId = REQUEST_ID) {
  return {
    ok: false, request_id: requestId,
    error: { code, message: "request refused", retryable },
  };
}

