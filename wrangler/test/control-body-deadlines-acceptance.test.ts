test("ops gate (preserved): unauthenticated write is 401 before its body stream is pulled", async () => {
  const names: string[] = [];
  const env = {
    REDIRECT_MAPPINGS_JSON: "[]",
    REDIRECT_FALLBACK_CODE: "fallbackCode",
    CF_VERSION_METADATA: { id: "synthetic-ops-deployment" },
    OPS_CONTROL_TOKEN: "synthetic-ops-control-token-0123456789",
    OPS_CONFIG_WRITES_ENABLED: "1",
    TWO_BOT: {
      getByName: (name: string) => {
        names.push(name);
        return { fetch: async () => Response.json({ ok: true }) };
      },
    },
  } as unknown as Env;
  const ctx = { waitUntil() {} } as unknown as ExecutionContext;
  const body = manualStream();
  const init: RequestInit & { duplex?: "half" } = {
    method: "PUT",
    headers: { "content-type": "application/json" },
    body: body.stream,
    duplex: "half",
  };
  const response = await worker.fetch(
    new Request(`https://ops.invalid${OPS_CONFIG_PATH}`, init), env, ctx);
  assert.equal(response.status, 401);
  assert.equal(await response.text(), "unauthorized\n");
  assert.equal(body.state.pulls, 0, "refused before the body is read at all");
  assert.deepEqual(names, [], "refused request never reaches the DO");
});
