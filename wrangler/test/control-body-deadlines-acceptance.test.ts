/**
 * Acceptance tests (protected): one whole-body deadline per control reader.
 *
 * Contract under test: the ownership control body reader (`readChange`,
 * 1024-byte cap) and the ops control body reader (`readOpsBody`,
 * 16384-byte cap) each bound the ENTIRE body read by a single deadline of
 * 5000 ms — the same whole-read convention the internal-actions and
 * eventsub receivers already use — instead of awaiting each chunk and the
 * overflow cancellation without any budget:
 *
 * - a stream that never yields settles through the existing refusal
 *   return (`null`) at the deadline, not before it;
 * - a sub-cap trickle cannot renew the budget: chunks arriving inside the
 *   budget do not move the deadline, which is scheduled exactly once;
 * - byte overflow settles `null` promptly even when `reader.cancel()`
 *   never resolves (cancellation is attempted, never awaited);
 * - a stream error settles `null` promptly;
 * - the deadline timer is cleared on every exit (success, error,
 *   overflow, timeout): ticking far past the budget afterwards causes no
 *   late cancellation or other observable effect;
 * - a valid body that completes inside the budget still parses, a body of
 *   exactly the byte cap is accepted, and malformed / cap+1 bodies keep
 *   the existing `null` refusal.
 *
 * Preserved behavior also pinned here: the ops Worker gate refuses an
 * unauthenticated mutating request before its body stream is pulled at
 * all (auth before body read) and never forwards it to the DO. Epoch
 * fencing, token comparison and the mutation gates themselves stay
 * covered by ownership.test.ts / ops-control.test.ts, which must keep
 * passing unchanged.
 *
 * These tests were written test-first against a baseline where both
 * readers enforce only the byte cap: `await reader.read()` has no
 * deadline and the overflow path awaits `reader.cancel()`. The deadline
 * and stalled-cancel tests are expected to FAIL there (the tracked read
 * never settles, and no 5000 ms timer is ever scheduled) and PASS once
 * both readers mirror the receiver pattern (one raced whole-read timer,
 * non-awaited best-effort cancellation, timer cleared in a `finally`).
 * The refusal value on timeout/error/overflow stays the existing `null`;
 * do not invent a new return shape, budget or response semantics to make
 * these pass. Do not edit this file to make an implementation pass; fix
 * the implementation.
 *
 * Fake timers only (node:test mock timers, `setTimeout`); every stream is
 * synthetic and in-memory. No Discord, database, deployed Worker, token
 * or mutation is contacted. Reads that would hang on the baseline are
 * tracked, never awaited directly, so RED evidence is a failed assertion
 * rather than a hung runner.
 * Run: node --import ./test/cloudflare-loader.mjs --test test/control-body-deadlines-acceptance.test.ts
 */
import { test, type TestContext } from "node:test";
import assert from "node:assert/strict";
import { setImmediate } from "node:timers/promises";
import worker, { type Env } from "../src/index.ts";
import { readChange } from "../src/ownership.ts";
import { MAX_OPS_BODY_BYTES, OPS_CONFIG_PATH, readOpsBody } from "../src/ops-control.ts";

/** The existing receiver whole-read convention both readers must adopt. */
const DEADLINE_MS = 5_000;
const OWNERSHIP_CAP_BYTES = 1024;

const encode = (text: string) => new TextEncoder().encode(text);

/** A JSON ownership change padded to exactly `cap` bytes (extra keys are ignored by the parser). */
function ownershipBody(cap: number): string {
  const base = JSON.stringify({ action: "fence", expectedEpoch: 0, actor: "fixture-operator", pad: "" });
  return JSON.stringify({
    action: "fence", expectedEpoch: 0, actor: "fixture-operator", pad: "x".repeat(cap - base.length),
  });
}

/** A JSON object of exactly `cap` bytes for the shape-agnostic ops reader. */
function opsBody(cap: number): string {
  const base = JSON.stringify({ pad: "" });
  return JSON.stringify({ pad: "x".repeat(cap - base.length) });
}

interface ReaderSpec {
  name: string;
  cap: number;
  read: (request: Request) => Promise<unknown>;
  /** Body text of exactly `cap` bytes that must be accepted. */
  exactCapBody: string;
  /** The value the reader returns for `exactCapBody`. */
  exactCapValue: unknown;
  /** Small valid body and its parsed value. */
  smallBody: string;
  smallValue: unknown;
}

const READERS: ReaderSpec[] = [
  {
    name: "ownership readChange",
    cap: OWNERSHIP_CAP_BYTES,
    read: (request) => readChange(request),
    exactCapBody: ownershipBody(OWNERSHIP_CAP_BYTES),
    exactCapValue: { action: "fence", expectedEpoch: 0, actor: "fixture-operator" },
    smallBody: JSON.stringify({ action: "takeover", expectedEpoch: 3, actor: "fixture-operator" }),
    smallValue: { action: "takeover", expectedEpoch: 3, actor: "fixture-operator" },
  },
  {
    name: "ops readOpsBody",
    cap: MAX_OPS_BODY_BYTES,
    read: (request) => readOpsBody(request),
    exactCapBody: opsBody(MAX_OPS_BODY_BYTES),
    exactCapValue: JSON.parse(opsBody(MAX_OPS_BODY_BYTES)),
    smallBody: JSON.stringify({ overrides: {}, expectedEpoch: 0, actor: "fixture-operator" }),
    smallValue: { overrides: {}, expectedEpoch: 0, actor: "fixture-operator" },
  },
];

/**
 * A manually driven stream: the test enqueues/closes, pulls are counted,
 * and the cancel hook either resolves at once or never settles.
 */
function manualStream(opts: { cancelStalls?: boolean } = {}) {
  let controller!: ReadableStreamDefaultController<Uint8Array>;
  const state = { pulls: 0, cancels: 0 };
  const stream = new ReadableStream<Uint8Array>({
    start(c) { controller = c; },
    pull() { state.pulls++; },
    cancel() {
      state.cancels++;
      if (opts.cancelStalls) return new Promise<void>(() => {});
    },
  }, { highWaterMark: 0 });
  return {
    stream,
    state,
    enqueue: (chunk: Uint8Array) => controller.enqueue(chunk),
    close: () => controller.close(),
  };
}

function streamRequest(stream: ReadableStream<Uint8Array>): Request {
  const init: RequestInit & { duplex?: "half" } = {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: stream,
    duplex: "half",
  };
  return new Request("https://worker.invalid/control", init);
}

/** Track a possibly-hanging read without ever awaiting it directly. */
function track(promise: Promise<unknown>) {
  const state: { settled: boolean; value: unknown; error: unknown } = {
    settled: false, value: undefined, error: undefined,
  };
  void promise.then(
    (value) => { state.settled = true; state.value = value; },
    (error) => { state.settled = true; state.error = error; },
  );
  return state;
}

/** Drain pending microtasks/immediates without touching the fake clock. */
async function flush(rounds = 3): Promise<void> {
  for (let i = 0; i < rounds; i++) await setImmediate();
}

/**
 * Enable fake `setTimeout` and record every scheduled delay and every
 * `clearTimeout` call, so a test can pin "exactly one 5000 ms timer per
 * read" and "timer cleared on exit" directly instead of inferring them.
 */
function trackTimers(t: TestContext) {
  t.mock.timers.enable({ apis: ["setTimeout"] });
  const scheduled: unknown[] = [];
  const cleared: unknown[] = [];
  const realSet = globalThis.setTimeout;
  const realClear = globalThis.clearTimeout;
  t.mock.method(globalThis, "setTimeout", (fn: never, ms?: never, ...rest: never[]) => {
    scheduled.push(ms);
    return (realSet as (...a: unknown[]) => unknown)(fn, ms, ...rest);
  });
  t.mock.method(globalThis, "clearTimeout", (handle?: never) => {
    cleared.push(handle);
    return (realClear as (...a: unknown[]) => unknown)(handle);
  });
  return {
    deadlineTimers: () => scheduled.filter((ms) => ms === DEADLINE_MS).length,
    clears: () => cleared.length,
  };
}

for (const spec of READERS) {
  test(`${spec.name}: stream that never yields settles null at the whole-body deadline`, async (t) => {
    const timers = trackTimers(t);
    const body = manualStream();
    const read = track(spec.read(streamRequest(body.stream)));
    await flush();
    assert.equal(read.settled, false, "no refusal before any time passes");
    t.mock.timers.tick(DEADLINE_MS - 1);
    await flush();
    assert.equal(read.settled, false, "deadline is the full 5000 ms, not shorter");
    t.mock.timers.tick(1);
    await flush();
    assert.equal(read.settled, true, "stalled read settles at the deadline instead of holding the caller");
    assert.equal(read.error, undefined, "timeout uses the refusal return, never a throw");
    assert.equal(read.value, null);
    assert.equal(timers.deadlineTimers(), 1, "exactly one 5000 ms whole-body timer per read");
    assert.ok(body.state.cancels >= 1, "timed-out stream cleanup is attempted");
    assert.ok(timers.clears() >= 1, "timer cleanup runs on the timeout exit");
  });

  test(`${spec.name}: sub-cap trickle cannot renew the budget`, async (t) => {
    const timers = trackTimers(t);
    const body = manualStream();
    const read = track(spec.read(streamRequest(body.stream)));
    await flush();
    body.enqueue(encode("{"));
    await flush();
    t.mock.timers.tick(4_000);
    body.enqueue(encode(" "));
    await flush();
    assert.equal(read.settled, false, "still inside the original budget");
    // 4999 ms since the read started but only 999 ms since the last chunk:
    // a per-chunk budget would still be waiting well past this point.
    t.mock.timers.tick(999);
    await flush();
    assert.equal(read.settled, false, "deadline is measured from the start of the read");
    t.mock.timers.tick(1);
    await flush();
    assert.equal(read.settled, true, "trickle settles at the original deadline");
    assert.equal(read.error, undefined);
    assert.equal(read.value, null);
    assert.equal(timers.deadlineTimers(), 1, "the deadline is scheduled once, never renewed per chunk");
  });

  test(`${spec.name}: overflow settles null promptly even when cancel never resolves`, async (t) => {
    const timers = trackTimers(t);
    const body = manualStream({ cancelStalls: true });
    const read = track(spec.read(streamRequest(body.stream)));
    await flush();
    body.enqueue(new Uint8Array(spec.cap + 1));
    await flush();
    assert.equal(read.settled, true, "overflow refusal never awaits a stalling cancellation");
    assert.equal(read.error, undefined);
    assert.equal(read.value, null);
    assert.ok(body.state.cancels >= 1, "cancellation is attempted best-effort");
    assert.ok(timers.clears() >= 1, "timer cleanup runs on the overflow exit");
    const cancels = body.state.cancels;
    t.mock.timers.tick(DEADLINE_MS * 2);
    await flush();
    assert.equal(body.state.cancels, cancels, "no late timer effect after the overflow exit");
  });

  test(`${spec.name}: erroring stream settles null promptly and clears the timer`, async (t) => {
    const timers = trackTimers(t);
    const stream = new ReadableStream<Uint8Array>({
      start(controller) { controller.error(new Error("synthetic stream failure")); },
    });
    const read = track(spec.read(streamRequest(stream)));
    await flush();
    assert.equal(read.settled, true, "stream error settles without waiting for the deadline");
    assert.equal(read.error, undefined, "stream error uses the refusal return, never a throw");
    assert.equal(read.value, null);
    assert.ok(timers.clears() >= 1, "timer cleanup runs on the error exit");
  });

  test(`${spec.name}: valid body inside the budget parses; timer cleared, no late cancel`, async (t) => {
    const timers = trackTimers(t);
    const body = manualStream();
    const read = track(spec.read(streamRequest(body.stream)));
    await flush();
    const bytes = encode(spec.smallBody);
    body.enqueue(bytes.slice(0, 8));
    await flush();
    t.mock.timers.tick(DEADLINE_MS - 1);
    body.enqueue(bytes.slice(8));
    body.close();
    await flush();
    assert.equal(read.settled, true, "a body completing at 4999 ms is inside the budget");
    assert.equal(read.error, undefined);
    assert.deepEqual(read.value, spec.smallValue);
    assert.ok(timers.clears() >= 1, "timer cleanup runs on the success exit");
    t.mock.timers.tick(DEADLINE_MS * 2);
    await flush();
    assert.equal(body.state.cancels, 0, "a leaked timer must not cancel a completed read");
    assert.deepEqual(read.value, spec.smallValue, "settled value is stable after the budget passes");
  });

  test(`${spec.name} (preserved): exact-cap accepted; malformed and cap+1 stay null`, async (t) => {
    trackTimers(t);
    assert.equal(encode(spec.exactCapBody).byteLength, spec.cap, "fixture is exactly the cap");
    const exact = track(spec.read(new Request("https://worker.invalid/control", {
      method: "POST", headers: { "content-type": "application/json" }, body: spec.exactCapBody,
    })));
    await flush();
    assert.equal(exact.settled, true);
    assert.deepEqual(exact.value, spec.exactCapValue, "boundary-size JSON keeps the existing limit semantics");

    const malformed = track(spec.read(new Request("https://worker.invalid/control", {
      method: "POST", headers: { "content-type": "application/json" }, body: "{not json",
    })));
    await flush();
    assert.equal(malformed.settled, true);
    assert.equal(malformed.value, null, "malformed JSON keeps the existing refusal");

    const over = manualStream();
    const oversize = track(spec.read(streamRequest(over.stream)));
    await flush();
    over.enqueue(new Uint8Array(spec.cap + 1));
    await flush();
    assert.equal(oversize.settled, true);
    assert.equal(oversize.value, null, "cap+1 keeps the existing refusal");
    assert.ok(over.state.cancels >= 1, "oversize stream is cancelled as today");
  });
}

