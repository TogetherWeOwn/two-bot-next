/**
 * Protected acceptance: optional webhook fan-out must not consume the 30-second
 * ownership gate or prevent durable observations and successor scheduling.
 *
 * Breaks caught: serial six-second allowances multiplying across a burst,
 * relying only on cooperative fetch abort, awaiting unbounded body cancellation,
 * dropping later transition logs/evaluation when forwarding runs out of time,
 * retrying ambiguous delivery, handling late failures without a rejection sink,
 * letting optional transport start after the forwarding cutoff or run past it,
 * posting before the successor schedule is inserted, and losing a received HTTP
 * status when body cancellation stalls or rejects.
 * No transport implementation or exact notification-budget constant is prescribed.
 *
 * The in-memory SDK/storage fixture follows container.test.ts's alertHarness;
 * metricsBody is the existing complete Rust-contract fixture. Only external I/O
 * is replaced. The gate callback is observed, not a simulation of Cloudflare's
 * event admission/reset machinery. No installed health or real SDK pipe release
 * is claimed. Fake time drives Date, timers AND AbortSignal.timeout.
 *
 * No live webhook, Worker, Discord, database or secret is used. Pending baseline
 * work is tracked rather than awaited, so a missing bound fails an assertion,
 * not the runner. Cleanup releases synthetic stalls after assertions only.
 * Do not edit this file to make the implementation pass; return corrections to
 * the test author. Run from wrangler:
 * node --import ./test/cloudflare-loader.mjs --test test/keepalive-notification-budget-acceptance.test.ts
 */
