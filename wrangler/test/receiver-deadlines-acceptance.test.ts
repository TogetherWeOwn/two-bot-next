/**
 * Acceptance tests (protected): one existing receiver deadline through the
 * whole DO-side relay for BOTH mirrored receiver routes — internal actions
 * (`POST /internal/actions`) and EventSub (`POST /hooks/twitch`).
 *
 * Contract under test: the receiver request deadline that the DO already
 * creates (`AbortSignal.timeout(REQUEST_TIMEOUT_MS)`, 20 s on both routes)
 * bounds wrapper fetch AND response-body reading inside the direct DO
 * handler — not only the outer Worker's race. A permitted response with a
 * small prefix and a stalled tail, a fetch that ignores abort, a response
 * that only arrives after the deadline, or a `cancel()` that never settles
 * must none of them hold the direct DO handler (and with it the DO
 * concurrency gate / `owned` section) past that existing budget. Cleanup is
 * best-effort, and a settled stall leaves the DO able to serve the next
 * request. No larger or independent timeout budget may appear.
 *
 * Preserved behavior: the fixed payload-safe refusal envelope (503,
 * `unavailable`, fixed message, honored `x-request-id`), body admission at
 * exactly the cap (EventSub JSON projects its supported envelope; internal
 * actions retain bytes), exact valid EventSub challenge bytes,
 * permitted status/header vocabulary, ownership fence, cold-container
 * refusal, and exactly one container fetch per request — a signed action is
 * NEVER retried automatically, and nothing here asserts that a wrapper
 * timeout proves a receiver mutation did not occur.
 *
 * Baseline (written test-first): the DO handlers build the timeout signal
 * for the forwarded request but then directly await `containerFetch` and
 * the relay without enforcing that deadline through the fetch or the body
 * read, and the relays await `reader.read()` / `cancel()` with no deadline.
 * The deadline tests below are expected to FAIL there (each hits the settle
 * guard) and PASS once the existing deadline is threaded through fetch and
 * body relay on both routes. Tests named "(preserved)" are controls: they
 * pass on the baseline and must keep passing. Do not edit this file to make
 * an implementation pass; fix the implementation.
 *
 * Verification limitations (state, do not claim more): `containerFetch` is
 * mocked past the Containers SDK proxy pipe, exactly as the refusal cases
 * in internal-actions.test.ts / eventsub.test.ts serve fixtures past the
 * pipe. These tests therefore prove caller settlement against a mocked
 * transport; they do NOT prove the SDK's internal proxy pipe settles, and
 * no SDK repair may be claimed from them. The harness
 * `blockConcurrencyWhile` invokes its callback immediately and does not
 * model DO input-gate queuing, so "following work proceeds" is observed as:
 * the stalled direct handler itself settles, then a subsequent direct
 * request on the same DO completes normally.
 *
 * Runtime storage/TCP are in-memory; every value is synthetic. No Discord,
 * Twitch, database, deployed Worker, signing secret or guild is contacted.
 * The production 20000 ms `AbortSignal.timeout` is shrunk to 30 ms and
 * asserted by value.
 * Run: node --import ./test/cloudflare-loader.mjs --test test/receiver-deadlines-acceptance.test.ts
 */
