/**
 * Shrink only the existing receiver deadline (20000 ms on both routes) to
 * 30 ms and hand back the mock so a test can assert production really
 * requested that budget and no larger one.
 */
function shrinkDeadline(t: TestContext, timeoutMs: number) {
  const realTimeout = AbortSignal.timeout;
  return t.mock.method(AbortSignal, "timeout", (ms: number) => realTimeout(ms === timeoutMs ? 30 : ms));
}

function assertExistingBudget(timeout: ReturnType<typeof shrinkDeadline>, route: Route): void {
  const asked = timeout.mock.calls.map((call) => call.arguments[0] as number);
  assert.ok(asked.includes(route.timeoutMs),
    `${route.label} must request the existing ${route.timeoutMs}ms receiver deadline (asked: ${asked.join(",")})`);
  assert.ok(asked.every((ms) => ms <= route.timeoutMs),
    `${route.label} must not create a larger budget (asked: ${asked.join(",")})`);
}

/**
 * Fail (do not hang) when the caller does not settle inside the budget.
 * On the unfixed baseline this rejection is the RED evidence: the awaited
 * fetch/body/cancel never settles, so the guard fires first.
 */
async function settleWithin<T>(work: Promise<T>, label: string, ms = SETTLE_BUDGET_MS): Promise<T> {
  let timer: ReturnType<typeof setTimeout> | undefined;
  const guard = new Promise<never>((_, reject) => {
    timer = setTimeout(() => reject(new Error(`${label} did not settle within ${ms}ms of a 30ms deadline`)), ms);
  });
  try {
    return await Promise.race([work, guard]);
  } finally {
    clearTimeout(timer);
  }
}

/** A stream that yields an optional prefix chunk, then stalls forever; its cancel also never resolves. */
function stalledStream(prefix: string | undefined, onCancel?: () => void) {
  let pulled = false;
  return new ReadableStream<Uint8Array>({
    pull(controller) {
      if (prefix !== undefined && !pulled) {
        pulled = true;
        controller.enqueue(new TextEncoder().encode(prefix));
        return;
      }
      return new Promise<void>(() => {});
    },
    cancel() {
      onCancel?.();
      return new Promise<void>(() => {});
    },
  }, { highWaterMark: 0 });
}

/** A stream whose cancel hook runs but whose cancel promise never resolves. */
function cancelStallStream(onCancel: () => void) {
  return new ReadableStream<Uint8Array>({
    pull() {},
    cancel() {
      onCancel();
      return new Promise<void>(() => {});
    },
  }, { highWaterMark: 0 });
}

/** One over-cap chunk, then a cancel (reader- or body-level) that never resolves. */
function oversizeCancelStallStream(bytes: number, onCancel: () => void) {
  let delivered = false;
  return new ReadableStream<Uint8Array>({
    pull(controller) {
      if (!delivered) {
        delivered = true;
        controller.enqueue(new Uint8Array(bytes).fill(0x7a));
        return;
      }
      return new Promise<void>(() => {});
    },
    cancel() {
      onCancel();
      return new Promise<void>(() => {});
    },
  }, { highWaterMark: 0 });
}

function jsonResponse(stream: ReadableStream<Uint8Array>, status = 200): Response {
  return new Response(stream, { status, headers: { "content-type": "application/json" } });
}

interface FetchCall { port: unknown; signal: AbortSignal | undefined; pathname: string }

function stubFetch(t: TestContext, bot: TwoBotContainer, impl: (call: FetchCall) => Promise<Response>) {
  const calls: FetchCall[] = [];
  t.mock.method(bot, "containerFetch", (input: unknown, port?: unknown) => {
    const call: FetchCall = {
      port,
      signal: input instanceof Request ? input.signal : undefined,
      pathname: new URL(typeof input === "string" ? input : (input as Request).url).pathname,
    };
    calls.push(call);
    return impl(call);
  });
  return calls;
}

/** The one fixed, payload-safe refusal every deadline path must settle with. */
async function assertFixedRefusal(response: Response, label: string): Promise<void> {
  assert.equal(response.status, 503, label);
  assert.equal(response.headers.get("cache-control"), "no-store", label);
  const text = await response.text();
  assert.ok(!text.includes(SENTINEL), `${label}: stalled/late prefix must never leave`);
  assert.ok(!text.includes(KEYS), `${label}: no upstream text may leave`);
  const body = JSON.parse(text) as { ok: boolean; request_id: string; error: Record<string, unknown> };
  assert.equal(body.ok, false);
  assert.equal(body.request_id, SENT_ID, `${label}: honored request id joins the refusal`);
  assert.ok(isRequestId(body.request_id));
  assert.deepEqual(body.error, { code: "unavailable", message: "request refused", retryable: true });
}

