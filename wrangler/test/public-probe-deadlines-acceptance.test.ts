/**
 * Acceptance tests (protected): public /health and /readyz probes stay
 * bounded through transport failure AND rejected-response cleanup.
 *
 * Contract under test: the public probe paths use ONE existing six-second
 * deadline across the container fetch and the consumption of a rejected
 * (non-bot) response body, and rejected-body cancellation is best-effort
 * at both the Durable Object and the outer Worker layer:
 *
 * - a container fetch that ignores abort and never resolves settles the
 *   caller at the deadline with the fixed `container_unavailable` refusal;
 * - a rejected response whose body yields a small sub-cap prefix and then
 *   stalls forever cannot extend caller settlement past the deadline
 *   (the byte cap alone never fires on a sub-cap stall);
 * - an abort-shaped response (the SDK resolves an aborted fetch as a 500
 *   text response) whose body then stalls still settles at the deadline;
 * - a response that only arrives after the deadline is discarded: it
 *   cannot delay or replace the fixed refusal, its body is released
 *   best-effort, and no upstream sentinel bytes leak into the refusal
 *   body or the logs;
 * - a `body.cancel()` whose promise never resolves cannot delay the
 *   fixed refusal at either layer.
 *
 * Preserved behavior: bot 200 and JSON 503 probe answers forward
 * byte-for-byte (including multi-chunk streamed bodies), HEAD forwards
 * as HEAD, the outer Worker stamps its version/deployment headers, and
 * the ownership fence refuses before any container fetch. Rate limiting
 * and request-header stripping stay pinned by health-probes.test.ts;
 * oversize (over-cap) discard stays pinned by container.test.ts.
 *
 * These tests were written test-first against a baseline where the probe
 * deadline signal reached the container fetch but not the rejected-body
 * bounded read, and the outer Worker awaited rejected-body cancellation.
 * The deadline/cancellation tests are expected to FAIL there (each hits
 * the settle guard below) and PASS once the probe paths carry the same
 * deadline through body consumption and treat cancellation as
 * best-effort. Do not edit this file to make an implementation pass; fix
 * the implementation.
 *
 * Verification boundary: `containerFetch` and the DO stub are replaced
 * with synthetic fixtures, so these tests prove bounded settlement and
 * cleanup attempts of the wrapper handlers only. They do NOT prove that
 * the real container SDK proxy pipe or its internal request gate is
 * released when a mocked body is cancelled; that SDK behavior is outside
 * what a stubbed transport can observe and is not claimed here.
 *
 * Runtime storage/TCP are in-memory; all env values are synthetic. No
 * Discord, database, deployed Worker, Docker daemon or secret bindings
 * are contacted. The production 6000 ms `AbortSignal.timeout` is shrunk
 * to 30 ms and asserted by value (the runner cancels live waits near
 * ~5 s).
 * Run: node --import ./test/cloudflare-loader.mjs --test test/public-probe-deadlines-acceptance.test.ts
 */
