async function harness(t: TestContext) {
  const database = new DatabaseSync(":memory:");
  t.after(() => database.close());
  const logs: string[] = [];
  for (const method of ["log", "warn", "error"] as const) {
    t.mock.method(console, method, (...args: unknown[]) => {
      logs.push(args.map(String).join(" "));
    });
  }
  const values = new Map<string, unknown>([[OWNER_KEY, ACTIVE_OWNER]]);
  const gates: Promise<unknown>[] = [];
  const runtime = {
    running: false,
    async destroy() { this.running = false; },
    start() { this.running = true; },
    monitor: () => new Promise<void>(() => {}),
    getTcpPort: () => ({
      async fetch() { throw new Error("fixture TCP must not be reached: containerFetch is mocked"); },
    }),
  };
  const ctx = {
    exports: { ContainerProxy: () => ({ fetch: () => { throw new Error("unexpected outbound request"); } }) },
    id: { toString: () => "synthetic-do-id" },
    container: runtime,
    storage: {
      get: async (key: string) => values.get(key),
      put: async (key: string | Record<string, unknown>, value?: unknown) => {
        if (typeof key === "string") values.set(key, value);
        else for (const [k, v] of Object.entries(key)) values.set(k, v);
      },
      delete: async (key: string) => values.delete(key),
      kv: {
        get: (key: string) => values.get(key),
        put: (key: string, value: unknown) => { values.set(key, value); },
        delete: (key: string) => values.delete(key),
      },
      sql: {
        exec(query: string, ...bindings: (string | number | null)[]) {
          return database.prepare(query).all(...bindings);
        },
      },
      setAlarm: async () => {},
      deleteAlarm: async () => {},
      sync: async () => {},
    },
    blockConcurrencyWhile<T>(callback: () => Promise<T>) {
      const promise = callback();
      gates.push(promise);
      return promise;
    },
  };
  const bot = new TwoBotContainer(
    ctx as unknown as DurableObjectState<{}>,
    { CF_VERSION_METADATA: { id: ID }, OWNERSHIP_CONTROL_TOKEN: CONTROL_TOKEN, ...WORKER_ENV } as Env,
  );
  await Promise.all(gates);
  return { bot, logs, values, ctx, database };
}

/**
 * Shrink only the production 6000 ms deadline to 30 ms and hand back the
 * mock so a test can assert the production code really requested 6000.
 */
function shrinkDeadline(t: TestContext) {
  const realTimeout = AbortSignal.timeout;
  return t.mock.method(AbortSignal, "timeout", (ms: number) => realTimeout(ms === 6000 ? 30 : ms));
}

/**
 * Fail (do not hang) when the caller does not settle inside the budget.
 * On the unfixed baseline this rejection is the RED evidence: the awaited
 * fetch/body/cancel never settles, so the guard fires first.
 */
async function settleWithin<T>(work: Promise<T>, label: string, ms = SETTLE_BUDGET_MS): Promise<T> {
  let timer: ReturnType<typeof setTimeout> | undefined;
  const guard = new Promise<never>((_, reject) => {
    timer = setTimeout(() => reject(new Error(`${label} did not settle within ${ms}ms of a 30ms deadline`)), ms);
  });
  try {
    return await Promise.race([work, guard]);
  } finally {
    clearTimeout(timer);
  }
}

function signalOf(input: unknown, init?: RequestInit): AbortSignal | undefined {
  return init?.signal ?? (input instanceof Request ? input.signal : undefined);
}

/**
 * A stream that yields an optional small prefix chunk, then stalls
 * forever; its cancel hook runs but the cancel promise never resolves.
 * The prefix stays far below any byte cap, so only a deadline (never the
 * cap) can bound a reader of this body.
 */
function stalledStream(prefix?: string, onCancel?: () => void) {
  let pulled = false;
  return new ReadableStream<Uint8Array>({
    pull(controller) {
      if (prefix !== undefined && !pulled) {
        pulled = true;
        controller.enqueue(new TextEncoder().encode(prefix));
        return;
      }
      return new Promise<void>(() => {});
    },
    cancel() {
      onCancel?.();
      return new Promise<void>(() => {});
    },
  }, { highWaterMark: 0 });
}

/** A stream whose cancel hook runs but whose cancel promise never resolves. */
function cancelStallStream(onCancel: () => void) {
  return new ReadableStream<Uint8Array>({
    pull() {},
    cancel() {
      onCancel();
      return new Promise<void>(() => {});
    },
  }, { highWaterMark: 0 });
}

const NEVER_FETCH = () => new Promise<Response>(() => {});

function assertNoSentinel(body: string, logs: string[]) {
  assert.ok(!body.includes(SENTINEL), "fixed refusal must not carry upstream bytes");
  assert.ok(logs.every((line) => !line.includes(SENTINEL)), "logs must not carry upstream bytes");
}

// ---------------------------------------------------------------------------
// Direct Durable Object public probes (/health, /readyz)
// ---------------------------------------------------------------------------

for (const path of PROBE_PATHS) {
  test(`DO ${path}: fetch that ignores abort and never resolves settles as the fixed refusal at the deadline`, async (t) => {
    const h = await harness(t);
    const timeout = shrinkDeadline(t);
    let seenSignal: AbortSignal | undefined;
    t.mock.method(h.bot, "containerFetch", (input: unknown, init?: RequestInit) => {
      seenSignal = signalOf(input, init);
      return NEVER_FETCH();
    });
    const response = await settleWithin(
      h.bot.fetch(probeRequest(`https://worker.invalid${path}`)), `DO ${path} never-fetch`);
    assert.equal(response.status, 500);
    assert.deepEqual(await response.json(), FIXED_REFUSAL);
    assert.ok(seenSignal?.aborted, "the deadline signal fired");
    assert.ok(timeout.mock.calls.some((call) => call.arguments[0] === 6000),
      `${path} must request the 6 s deadline`);
  });

  test(`DO ${path}: rejected sub-cap stalled body settles as the fixed refusal at the deadline`, async (t) => {
    const h = await harness(t);
    shrinkDeadline(t);
    let cancelled = 0;
    // Non-bot shape (503 without a JSON body): the probe must consume and
    // discard it under the deadline. The prefix is a few dozen bytes, far
    // below the discard cap, and the tail never arrives.
    t.mock.method(h.bot, "containerFetch", async () => new Response(
      stalledStream(SENTINEL, () => { cancelled++; }),
      { status: 503, headers: { "content-type": "text/plain" } }));
    const response = await settleWithin(
      h.bot.fetch(probeRequest(`https://worker.invalid${path}`)), `DO ${path} rejected-stalled-body`);
    assert.equal(response.status, 500);
    const body = await response.text();
    assert.deepEqual(JSON.parse(body), FIXED_REFUSAL);
    assertNoSentinel(body, h.logs);
    assert.ok(cancelled >= 1, "stalled rejected body cleanup is attempted");
  });

  test(`DO ${path}: abort-shaped response whose body then stalls still settles as the fixed refusal`, async (t) => {
    const h = await harness(t);
    shrinkDeadline(t);
    let cancelled = 0;
    // The SDK resolves an aborted container fetch as a 500 text response
    // instead of rejecting; consuming that rejected body must remain
    // inside the same deadline even though the signal already fired.
    t.mock.method(h.bot, "containerFetch", (input: unknown, init?: RequestInit) =>
      new Promise<Response>((resolve) => {
        signalOf(input, init)?.addEventListener("abort", () => resolve(new Response(
          stalledStream(`Error proxying request to container: ${SENTINEL}`, () => { cancelled++; }),
          { status: 500, headers: { "content-type": "text/plain" } })), { once: true });
      }));
    const response = await settleWithin(
      h.bot.fetch(probeRequest(`https://worker.invalid${path}`)), `DO ${path} abort-shaped-stalled-body`);
    assert.equal(response.status, 500);
    const body = await response.text();
    assert.deepEqual(JSON.parse(body), FIXED_REFUSAL);
    assertNoSentinel(body, h.logs);
    await setImmediate();
    assert.ok(cancelled >= 1, "abort-shaped body cleanup is attempted");
  });

  test(`DO ${path}: late response after the deadline is discarded and cannot replace the fixed refusal`, async (t) => {
    const h = await harness(t);
    shrinkDeadline(t);
    let cancelled = 0;
    let release: (() => void) | undefined;
    t.mock.method(h.bot, "containerFetch", () => new Promise<Response>((resolve) => {
      release = () => resolve(new Response(
        cancelStallStream(() => { cancelled++; }),
        { status: 200, headers: { "content-type": "application/json" } }));
    }));
    const response = await settleWithin(
      h.bot.fetch(probeRequest(`https://worker.invalid${path}`)), `DO ${path} late-response`);
    assert.equal(response.status, 500);
    const body = await response.text();
    assert.deepEqual(JSON.parse(body), FIXED_REFUSAL);
    release!();
    await setImmediate();
    await setImmediate();
    assert.ok(cancelled >= 1, "late response body is released best-effort");
    assertNoSentinel(body, h.logs);
  });
}

